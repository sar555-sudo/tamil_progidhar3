function openModal(poojaId) {
  const data = poojaDetails[poojaId];
  if (!data) return;

  modalTitle.textContent = data.title;
  modalSubtitle.textContent = data.subtitle;

  // Set dynamic section titles (fallback to default hard-coded text if missing)
  if (modalWhenTitle) {
    modalWhenTitle.textContent =
      data.whenTitle || "இந்த வழிபாடு எப்போது செய்யலாம்?";
  }
  if (modalBenefitsTitle) {
    modalBenefitsTitle.textContent = data.benefitsTitle || "செய்முறை:";
  }
  // Instructions section: show only when needed for this pooja
  const showInstructionsSection =
    data.showInstructionsSection !== false &&
    Array.isArray(data.instructions) &&
    data.instructions.length > 0;

  if (modalInstructionsSection) {
    modalInstructionsSection.style.display = showInstructionsSection ? "" : "none";
  }

  if (showInstructionsSection && modalInstructionsTitle) {
    modalInstructionsTitle.textContent =
      data.instructionsTitle || "பெயர் தேர்ந்தெடுப்பது எப்படி?";
  }

  // Ensure other sections are visible
  if (modalWhenSection) modalWhenSection.style.display = "";
  if (modalBenefitsSection) modalBenefitsSection.style.display = "";

  modalImage.className = "modal-image";
  if (data.imageClass) {
    modalImage.classList.add(data.imageClass);
  }

  // Clear previous list items safely
  [modalWhen, modalBenefits, modalInstructions, modalHome].forEach((ul) => {
    if (ul) ul.innerHTML = "";
  });

  // Populate "when" points, if provided
  if (Array.isArray(data.when) && modalWhen) {
    data.when.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      modalWhen.appendChild(li);
    });
  }

  // Populate "benefits" points, if provided
  if (Array.isArray(data.benefits) && modalBenefits) {
    data.benefits.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      modalBenefits.appendChild(li);
    });
  }

  // Populate "instructions" points only if section is shown
  if (showInstructionsSection && Array.isArray(data.instructions) && modalInstructions) {
    data.instructions.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      modalInstructions.appendChild(li);
    });
  }

  // Home section: show only when needed for this pooja
  const showHomeSection = Array.isArray(data.home) && data.home.length > 0;
  if (modalHomeSection) {
    modalHomeSection.style.display = showHomeSection ? "" : "none";
  }
  if (showHomeSection && modalHomeTitle) {
    modalHomeTitle.textContent = data.homeTitle || "இல்லத்தில் ஏற்றல்(வீட்டிற்கு அழைத்தல்) என்றால் என்ன?";
  }
  // Populate "home" points only if section is shown
  if (showHomeSection && Array.isArray(data.home) && modalHome) {
    data.home.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      modalHome.appendChild(li);
    });
  }

  // Time section: show only when needed for this pooja
  const showTimeSection = Array.isArray(data.time) && data.time.length > 0;
  if (modaltimeSection) {
    modaltimeSection.style.display = showTimeSection ? "" : "none";
  }
  if (showTimeSection && modaltimeTitle) {
    modaltimeTitle.textContent =
      data.timeTitle || data.timetitle || "நாள் & நேரம்:";
  }
  // Populate "time" points only if section is shown
  if (showTimeSection && Array.isArray(data.time) && modaltime) {
    data.time.forEach((item) => {
      const li = document.createElement("li");
      li.textContent = item;
      modaltime.appendChild(li);
    });
  }

  modalBackdrop.classList.add("active");
  modalBackdrop.setAttribute("aria-hidden", "false");
}

function closeModal() {
  modalBackdrop.classList.remove("active");
  modalBackdrop.setAttribute("aria-hidden", "true");
}

